"""Offline tests for the static PE inventory used by gms-compat inspect.

All fixtures are synthetic images generated by tests/gms_compat_pe_fixture.py.
No vendor module is loaded, resolved or executed by any test here.
"""
import json
import os
import sys
import tempfile
import unittest

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
for _path in (os.path.join(_ROOT, "tools", "gms_compat"), _HERE):
    if _path not in sys.path:
        sys.path.insert(0, _path)

import cli  # noqa: E402
import gms_compat_pe_fixture as fixtures  # noqa: E402
import pe  # noqa: E402


def _exports(*names):
    return [{"name": name} for name in names]


class InspectPeTests(unittest.TestCase):
    def setUp(self):
        self._directory = tempfile.TemporaryDirectory()
        self.addCleanup(self._directory.cleanup)
        self.root = self._directory.name

    def write(self, name, **kwargs):
        return fixtures.write_pe(os.path.join(self.root, name), **kwargs)

    def test_reads_version_architecture_and_hash(self):
        path = self.write("Known.dll", machine="x64", file_version=(3, 53, 4137, 0),
                          exports=_exports("?Alpha@Demo@@QAEXXZ", "Beta"))
        record = pe.inspect_module(path)
        self.assertEqual(record["version"]["file_version"], "3.53.4137.0")
        self.assertEqual(record["version"]["source"], "vs_fixed_file_info")
        self.assertEqual(record["architecture"], "x64")
        self.assertEqual(record["pe"]["format"], "pe32+")
        self.assertRegex(record["sha256"], r"^[0-9a-f]{64}$")
        self.assertEqual(record["export_summary"]["count"], 2)

    def test_hash_tracks_content_not_name(self):
        first = self.write("One.dll", exports=_exports("Alpha"))
        renamed = fixtures.write_pe(os.path.join(self.root, "Two.dll"),
                                    exports=_exports("Alpha"))
        other = self.write("Three.dll", exports=_exports("Alpha", "Beta"))
        self.assertEqual(pe.inspect_module(first)["sha256"],
                         pe.inspect_module(renamed)["sha256"])
        self.assertNotEqual(pe.inspect_module(first)["sha256"],
                            pe.inspect_module(other)["sha256"])

    def test_x86_and_x64_are_distinguished(self):
        x86 = pe.inspect_module(self.write("Tiny.dll", machine="x86"))
        x64 = pe.inspect_module(self.write("Wide.dll", machine="x64"))
        self.assertEqual(x86["architecture"], "x86")
        self.assertEqual(x86["pe"]["format"], "pe32")
        self.assertEqual(x64["architecture"], "x64")
        self.assertEqual(x64["pe"]["format"], "pe32+")

    def test_forwarded_export_is_reported_as_forwarder(self):
        record = pe.inspect_module(self.write("Fwd.dll", exports=[
            {"name": "Local"},
            {"name": "Remote", "forward": "OTHER.Thing"},
        ]))
        by_name = dict((entry["name"], entry) for entry in record["exports"])
        self.assertIsNone(by_name["Local"]["forwarder"])
        self.assertTrue(by_name["Local"]["executable"])
        self.assertEqual(by_name["Remote"]["forwarder"], "OTHER.Thing")
        self.assertFalse(by_name["Remote"]["executable"])
        self.assertEqual(record["export_summary"]["forwarded"], 1)

    def test_imported_modules_are_listed_deterministically(self):
        record = pe.inspect_module(self.write("Imp.dll", imports={
            "KERNEL32.dll": ["GetLastError"],
            "USER32.dll": ["MessageBoxW", "GetDesktopWindow"],
        }))
        self.assertEqual([item["module"] for item in record["imports"]],
                         ["KERNEL32.dll", "USER32.dll"])
        self.assertEqual(record["imports"][1]["function_count"], 2)

    def test_missing_version_resource_is_explicit(self):
        record = pe.inspect_module(self.write("Bare.dll", with_version=False))
        self.assertIsNone(record["version"]["file_version"])
        self.assertEqual(record["version"]["source"], "absent")

    def test_truncated_input_reports_a_stable_code(self):
        path = self.write("Cut.dll", exports=_exports("Alpha"))
        with open(path, "rb") as handle:
            payload = handle.read()
        with open(path, "wb") as handle:
            handle.write(payload[:0x20])
        with self.assertRaises(pe.PeFormatError) as caught:
            pe.inspect_module(path)
        self.assertEqual(caught.exception.code, "pe_dos_header_truncated")
        with open(path, "wb") as handle:
            handle.write(payload[:0x60])
        with self.assertRaises(pe.PeFormatError) as cut:
            pe.inspect_module(path)
        self.assertEqual(cut.exception.code, "pe_optional_header_truncated")

    def test_non_pe_input_is_rejected(self):
        path = os.path.join(self.root, "notes.txt")
        with open(path, "wb") as handle:
            handle.write(b"not a portable executable" + b"." * 128)
        with self.assertRaises(pe.PeFormatError) as caught:
            pe.inspect_module(path)
        self.assertEqual(caught.exception.code, "pe_dos_magic")

    def test_empty_and_missing_inputs_are_distinguished(self):
        empty = os.path.join(self.root, "Empty.bin")
        open(empty, "wb").close()
        with self.assertRaises(pe.PeFormatError) as caught:
            pe.inspect_module(empty)
        self.assertEqual(caught.exception.code, "pe_file_empty")
        with self.assertRaises(pe.PeFormatError) as missing:
            pe.inspect_module(os.path.join(self.root, "Absent.dll"))
        self.assertEqual(missing.exception.code, "pe_file_missing")

    def test_oversized_input_is_rejected_before_parsing(self):
        path = self.write("Big.dll")
        with self.assertRaises(pe.PeFormatError) as caught:
            pe.inspect_module(path, max_file_bytes=16)
        self.assertEqual(caught.exception.code, "pe_file_too_large")


class InspectCliTests(unittest.TestCase):
    def setUp(self):
        self._directory = tempfile.TemporaryDirectory()
        self.addCleanup(self._directory.cleanup)
        self.root = self._directory.name

    def run_cli(self, argv):
        from io import StringIO
        from contextlib import redirect_stdout, redirect_stderr
        out, err = StringIO(), StringIO()
        with redirect_stdout(out), redirect_stderr(err):
            code = cli.main(argv)
        return code, out.getvalue(), err.getvalue()

    def test_report_is_reproducible_byte_for_byte(self):
        path = fixtures.write_pe(os.path.join(self.root, "Stable.dll"),
                                 exports=_exports("Alpha", "Beta"))
        first = self.run_cli(["inspect", path])
        second = self.run_cli(["inspect", path])
        self.assertEqual(first[0], 0)
        self.assertEqual(first[1], second[1])
        document = json.loads(first[1])
        self.assertTrue(document["inputs"]["read_only"])
        self.assertFalse(document["inputs"]["loaded_any_module"])
        self.assertFalse(document["inputs"]["executed_any_target_code"])

    def test_default_disclosure_hides_the_local_directory(self):
        path = fixtures.write_pe(os.path.join(self.root, "Hidden.dll"))
        code, out, _ = self.run_cli(["inspect", path])
        self.assertEqual(code, 0)
        self.assertNotIn(self.root.replace("\\", "\\\\"), out)
        document = json.loads(out)
        self.assertEqual(document["modules"][0]["source"], "Hidden.dll")

    def test_none_disclosure_removes_the_path_entirely(self):
        path = fixtures.write_pe(os.path.join(self.root, "Hidden.dll"))
        code, out, _ = self.run_cli(["inspect", "--disclosure", "none", path])
        self.assertEqual(code, 0)
        self.assertIsNone(json.loads(out)["modules"][0]["source"])

    def test_relative_disclosure_requires_a_root(self):
        path = fixtures.write_pe(os.path.join(self.root, "Rel.dll"))
        code, _, err = self.run_cli(["inspect", "--disclosure", "relative", path])
        self.assertEqual(code, 2)
        self.assertIn("path_disclosure_requires_root", err)

    def test_directory_mode_sorts_modules_and_reports_bad_inputs(self):
        fixtures.write_pe(os.path.join(self.root, "b.dll"))
        fixtures.write_pe(os.path.join(self.root, "a.dll"))
        with open(os.path.join(self.root, "c.dll"), "wb") as handle:
            handle.write(b"garbage" * 32)
        code, out, _ = self.run_cli(["inspect", self.root])
        document = json.loads(out)
        self.assertEqual(code, 2)
        self.assertEqual([module["name"] for module in document["modules"]],
                         ["a.dll", "b.dll"])
        self.assertEqual(len(document["errors"]), 1)
        self.assertEqual(document["errors"][0]["code"], "pe_dos_magic")

    def test_directory_module_budget_is_enforced(self):
        for name in ("a.dll", "b.dll", "c.dll"):
            fixtures.write_pe(os.path.join(self.root, name))
        code, out, _ = self.run_cli(["inspect", "--max-modules", "2", self.root])
        document = json.loads(out)
        self.assertEqual(code, 2)
        self.assertEqual(len(document["modules"]), 2)
        self.assertEqual(document["errors"][0]["code"], "pe_directory_too_many_modules")


if __name__ == "__main__":
    unittest.main()
